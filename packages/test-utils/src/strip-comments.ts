/**
 * 注释剥离器 —— 全仓**唯一真源**（台账 N46 收敛，2026-10-02 债务清理批）。
 *
 * ⚠️ **为什么收敛到这一份**：此前跨包散着 8 份私有副本（api-gateway×3 / protocol /
 * robot-service / room-service×2 / user-service），分属**两套语义**：
 *  - **带 `:` 守卫**（本实现，源自 api-gateway 三份逐字相同的版本）：`//` 前是 `:` 时
 *    **不剥**（URL 里的 `//` 不会被当成行注释起点）⇒ 剥离结果「只多不少」；
 *  - **不带守卫**（其余五份）：`"http://evil/api/games"` 会被截成 `"http:` ⇒
 *    **真违规被自己的剥离器吃掉**（N46 登记的两处**实测可复现**假阴性：
 *    room-service 的内部 HTTP 判据、user-service 的 E7 `synchronize: true` 判据）。
 *
 *  收敛方向**只能**是守卫版：若反向收敛（以无守卫为准），api-gateway 三份闸会被**放宽**
 *  —— 违反 R435「不得放宽 §12 的任何一条闸」。各使用点的判据形态未变，判别力**不降**
 *  （两处假阴性在收敛后**看得见**了，见本包测试里的两个镜像用例）。
 *
 * ⚠️ **已知边界（如实钉住，见 test/strip-comments.test.ts）**：
 *  - **引号不感知**：字符串里出现非 `:` 前缀的 `//`（如 `'a//b'`）仍会被误剥；
 *    字符串里出现块注释开标记的场景也会错配。本仓被本工具服务的扫描面没有这两种形态
 *    （有一处更重的引号感知实现，在客户端侧 `apps/client/test/helpers/source-scan.ts`
 *    —— 那是**另一层契约**，射程不含本工具；台账 N46 的「客户端侧余量」条目）。
 *  - 手写状态机式的剥离器不落任何字面量 ⇒ 三层机械判据全逃，只能靠人评审
 *    （同 N46 的残余说明）。
 *
 * ⚠️ **顺序是语义**：先剥块注释、再逐行剥行注释 —— 反过来会把行注释里的块注释
 * 开标记当成块注释起点，把后面的**真代码**一起吃掉。
 */
export function stripComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}
